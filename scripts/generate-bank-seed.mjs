#!/usr/bin/env node
// Turns a bank list JSON ([{ name, slug, code }, ...]) into an idempotent seed migration.
//   node scripts/generate-bank-seed.mjs banks.json [supabase/migrations/005_seed_banks.sql]
// Safe to re-run with a fresher list: existing rows get name/code/category refreshed,
// while manual is_active / payout_eligible edits are preserved.
import fs from 'node:fs'
import path from 'node:path'

const [, , input = 'banks.json', output = 'supabase/migrations/005_seed_banks.sql'] = process.argv

const raw = JSON.parse(fs.readFileSync(input, 'utf8'))
const list = Array.isArray(raw) ? raw : raw.data
if (!Array.isArray(list)) throw new Error('Expected a JSON array (or { data: [...] })')

// ---- classification ---------------------------------------------------------
// Finance companies, mortgage banks and merchant banks can't be paid out to via
// normal NIP transfers, so they're kept in the table but hidden from the dropdown.
const FINANCE_COMPANIES = new Set([
  '78 finance company ltd', 'branch international finance company limited', 'county finance limited',
  'credit direct limited', 'fewchore finance company limited', 'pfi finance company limited',
  'prosperis finance limited', 'sage grey finance limited', 'vale finance limited',
  'whitecrust finance company', 'centrum finance',
])
const WALLET_SLUGS = new Set([
  'paycom', 'palmpay', 'paga', 'eyowo', 'gomoney', 'tangerine-money', 'pocket', 'zap',
  'xpress-wallet-ng', 'kongapay-tech-ltd', 'visual-ict-limited-tagpay-ng', 'parkway-ready-cash',
  'carbon', 'titan-paystack',
])
const OTHER_SLUGS = new Set(['vtnetworks-ng'])
// Same institution listed twice under different names/slugs: keep the first, retire the rest
const RETIRED_SLUGS = new Set(['bankit-microfinance-bank-ltd-ng', 'uc-microfinance-bank-ltd-u-and-c-mfb-ng'])

function categorize(name, slug) {
  const n = name.toLowerCase()
  if (OTHER_SLUGS.has(slug)) return 'other'
  if (FINANCE_COMPANIES.has(n)) return 'finance_company'
  if (/merchant bank/.test(n)) return 'merchant_bank'
  if (/mortgage|mortage|homes savings|savings and loans|building investment/.test(n)) return 'mortgage_bank'
  if (/\bpsb\b|payment service bank/.test(n)) return 'psb'
  if (WALLET_SLUGS.has(slug)) return 'wallet'
  if (/\bmfb\b|microfinance|mircofinance/.test(n)) return 'microfinance'
  return 'commercial'
}

// ---- normalise + validate -------------------------------------------------------
const seen = new Set()
const rows = []
for (const [i, b] of list.entries()) {
  const name = String(b?.name ?? '').replace(/\s+/g, ' ').trim()
  const slug = String(b?.slug ?? '').trim().toLowerCase()
  const code = String(b?.code ?? '').trim()
  if (!name || !slug || !code) throw new Error(`Row ${i}: name, slug and code are all required`)
  if (seen.has(slug)) throw new Error(`Duplicate slug "${slug}" (row ${i}). Slugs must be unique.`)
  seen.add(slug)
  const category = categorize(name, slug)
  rows.push({
    name, slug, code, category,
    payout_eligible: !['finance_company', 'merchant_bank', 'mortgage_bank', 'other'].includes(category),
    is_active: !RETIRED_SLUGS.has(slug),
  })
}
rows.sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }))

// ---- SQL --------------------------------------------------------------------------
const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const tuple = (r) => `  (${q(r.name)}, ${q(r.slug)}, ${q(r.code)}, ${q(r.category)}, ${r.payout_eligible}, ${r.is_active})`

const chunks = []
for (let i = 0; i < rows.length; i += 100) chunks.push(rows.slice(i, i + 100))

const sql = [
  `-- Generated by scripts/generate-bank-seed.mjs from ${path.basename(input)} (${rows.length} banks).`,
  `-- Idempotent: re-running refreshes name/code/category but keeps manual is_active / payout_eligible edits.`,
  '',
  ...chunks.map((c) =>
    `insert into public.banks (name, slug, code, category, payout_eligible, is_active) values\n${c.map(tuple).join(',\n')}\n` +
    `on conflict (slug) do update set\n  name = excluded.name,\n  code = excluded.code,\n  category = excluded.category,\n  updated_at = now();\n`,
  ),
].join('\n')

fs.mkdirSync(path.dirname(output), { recursive: true })
fs.writeFileSync(output, sql)

// ---- report -----------------------------------------------------------------------
const count = (f) => rows.filter(f).length
console.log(`Wrote ${rows.length} banks to ${output}`)
const byCat = {}
for (const r of rows) byCat[r.category] = (byCat[r.category] ?? 0) + 1
console.log('By category:', byCat)
console.log(`Shown in payout dropdown: ${count((r) => r.payout_eligible && r.is_active)}`)
console.log(`Hidden (not payout-eligible): ${count((r) => !r.payout_eligible)}`)
console.log(`Retired duplicates: ${count((r) => !r.is_active)}`)

const byCode = new Map()
for (const r of rows) byCode.set(r.code, [...(byCode.get(r.code) ?? []), r.name])
const clashes = [...byCode].filter(([, names]) => names.length > 1)
if (clashes.length) {
  console.log('\nBank codes shared by more than one entry (verify against your gateway\'s live list):')
  for (const [code, names] of clashes) console.log(`  ${code}: ${names.join('  |  ')}`)
}
